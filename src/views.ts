/** Agent-authored renderer modules (`display: "view:<name>"`): generation, static validation and file writes. */
import { createHash, randomUUID } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { resolve, sep } from 'node:path';
import { Script } from 'node:vm';
import { config } from './config.ts';
import { unifiedDiff } from './diff.ts';
import { HudError } from './store.ts';

export const VIEW_NAME_RE = /^[a-z0-9][a-z0-9._-]{0,63}$/;
export const VIEW_MAX_BYTES = 256 * 1024;
/** hud_view tool results stop at this many characters. A review that does not fit is not approvable. */
export const VIEW_REVIEW_MAX_CHARS = 60_000;

/** tests redirect module storage here; the server always uses config().viewsDir */
let dirOverride: string | null = null;
export function setViewsDir(dir: string | null): void {
  dirOverride = dir;
}
const viewsDir = () => dirOverride ?? config().viewsDir;

export const VIEW_KINDS = ['bar', 'line', 'sparkline', 'gauge', 'bullet', 'scatter', 'heatmap', 'table', 'slo'] as const;
export type ViewKind = (typeof VIEW_KINDS)[number];

export interface ViewSpec {
  kind: ViewKind;
  title?: string;
  /** dot path into item.meta, or "history" for series */
  series?: string;
  unit?: string;
  max?: number;
  targets?: { value: number; label?: string }[];
  thresholds?: { warn?: number; error?: number };
  bins?: number;
  maxRows?: number;
}

export interface ViewValidation {
  ok: boolean;
  errors: string[];
  warnings: string[];
  sha256: string;
}

const sha256 = (text: string | Buffer) => createHash('sha256').update(text).digest('hex');

export function normalizeViewName(name: string): string {
  const n = String(name ?? '').trim().replace(/\.js$/i, '');
  if (!VIEW_NAME_RE.test(n)) throw new HudError(400, 'view name must be 1-64 chars: lowercase letters, digits, . _ -');
  return n;
}

export function viewFilePath(name: string): string {
  const dir = resolve(viewsDir());
  const file = resolve(dir, `${normalizeViewName(name)}.js`);
  if (!file.startsWith(dir + sep)) throw new HudError(403, 'view path escapes the views directory');
  return file;
}

/** the module body shared by every template: neutral on the dark surface, sized to w/h, never throws */
function wrap(name: string, spec: ViewSpec, body: string): string {
  return `// generated by hud — see views/README.md. This module runs unsandboxed in the board page.
export const meta = ${JSON.stringify({ name, spec, generator: 'hud' }, null, 2)};

export function render({ item, w, h, helpers }) {
  const { esc, fmt, seriesOf, categoriesOf, pointsOf, gridOf, rangeOf, svg } = helpers;
  const spec = ${JSON.stringify(spec)};
  try {
${body.split('\n').map((line) => `    ${line}`).join('\n')}
  } catch (e) {
    return '<div style="padding:6px;color:#8c8c8c">view error: ' + esc(e && e.message) + '</div>';
  }
}
`;
}

export function generateViewCode(name: string, spec: ViewSpec): string {
  const n = normalizeViewName(name);
  if (!VIEW_KINDS.includes(spec.kind)) throw new HudError(400, `kind must be one of ${VIEW_KINDS.join('|')}`);
  const series = JSON.stringify(spec.series ?? (spec.kind === 'heatmap' ? 'grid' : spec.kind === 'scatter' ? 'points' : spec.kind === 'bar' ? 'categories' : ''));
  let body: string;
  switch (spec.kind) {
    case 'bar':
      body = `const data = categoriesOf(item, { series: ${series} });
if (!data.length) return '<div style="padding:6px;color:#8c8c8c">no categories at ' + esc(${series} || 'meta.categories') + '</div>';
const max = Math.max(1, ...data.map(d => Math.abs(d.value)));
const bw = w / data.length;
let out = '';
data.forEach((d, i) => {
  const bh = Math.max(1, Math.abs(d.value) / max * (h - 18));
  out += '<rect x="' + (i * bw + 1) + '" y="' + (h - 13 - bh) + '" width="' + Math.max(1, bw - 2) + '" height="' + bh + '" fill="#e8e8e8"/>';
  out += '<text x="' + (i * bw + bw / 2) + '" y="' + (h - 3) + '" fill="#8c8c8c" font-size="9" text-anchor="middle">' + esc(d.name) + '</text>';
});
return svg(item, 'gen-bar', w, h, out);`;
      break;
    case 'line':
    case 'sparkline':
      body = `const { pts } = seriesOf(item);
if (!pts.length) return '<div style="padding:6px;color:#8c8c8c">no history yet</div>';
const r = rangeOf(pts.map(p => p.v));
const x = (i) => 4 + (i / Math.max(1, pts.length - 1)) * (w - 8);
const y = (v) => h - 6 - ((v - r.lo) / (r.hi - r.lo || 1)) * (h - 12);
const d = pts.map((p, i) => (i ? 'L' : 'M') + x(i).toFixed(1) + ' ' + y(p.v).toFixed(1)).join(' ');
return svg(item, 'gen-line', w, h, '<path d="' + d + '" fill="none" stroke="#e8e8e8" stroke-width="1.4"/>');`;
      break;
    case 'gauge':
      body = `const value = Number(Object.hasOwn(item, 'value') ? item.value : 0);
const max = Number(spec.max ?? item.max ?? 100) || 100;
const pct = Math.max(0, Math.min(100, value / max * 100));
return svg(item, 'gen-gauge', w, h, '<rect x="6" y="' + (h / 2 - 5) + '" width="' + (w - 12) + '" height="10" rx="5" fill="#283140"/>' + '<rect x="6" y="' + (h / 2 - 5) + '" width="' + ((w - 12) * pct / 100) + '" height="10" rx="5" fill="#e6ebf2"/>' + '<text x="' + (w / 2) + '" y="' + (h / 2 - 12) + '" fill="#f6f8fb" font-size="13" text-anchor="middle">' + esc(fmt(value)) + (spec.unit ? esc(spec.unit) : '') + ' · ' + Math.round(pct) + '%</text>');`;
      break;
    case 'bullet':
      body = `const value = Number(Object.hasOwn(item, 'value') ? item.value : 0);
const max = Number(spec.max ?? item.max ?? Math.max(value * 1.2, 1)) || 1;
const scale = (v) => 6 + Math.max(0, Math.min(1, v / max)) * (w - 12);
const warn = spec.thresholds && spec.thresholds.warn, error = spec.thresholds && spec.thresholds.error;
const ticks = [[warn, '#9aa6b6'], [error, '#ff6d6d']].filter(t => Number.isFinite(t[0])).map(t => '<rect x="' + scale(t[0]) + '" y="' + (h / 2 - 10) + '" width="1" height="20" fill="' + t[1] + '"/>').join('');
const target = (spec.targets || []).map(t => Number(t.value)).filter(Number.isFinite).map(v => '<rect x="' + (scale(v) - 1) + '" y="' + (h / 2 - 12) + '" width="2" height="24" fill="#fff"/>').join('');
return svg(item, 'gen-bullet', w, h, '<rect x="6" y="' + (h / 2 - 4) + '" width="' + (w - 12) + '" height="8" fill="#2c2c2c"/>' + '<rect x="6" y="' + (h / 2 - 4) + '" width="' + (scale(value) - 6) + '" height="8" fill="#e8e8e8"/>' + ticks + target + '<text x="6" y="' + (h - 4) + '" fill="#8c8c8c" font-size="9">' + esc(fmt(value)) + (spec.unit ? ' ' + esc(spec.unit) : '') + '</text>');`;
      break;
    case 'scatter':
      body = `const pts = pointsOf(item, { series: ${series} });
if (!pts.length) return '<div style="padding:6px;color:#8c8c8c">no points at ' + esc(${series} || 'meta.points') + '</div>';
const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
const rx = rangeOf(xs), ry = rangeOf(ys);
const px = (v) => 6 + (v - rx.lo) / (rx.hi - rx.lo || 1) * (w - 12);
const py = (v) => h - 6 - (v - ry.lo) / (ry.hi - ry.lo || 1) * (h - 12);
return svg(item, 'gen-scatter', w, h, pts.map(p => '<circle cx="' + px(p[0]) + '" cy="' + py(p[1]) + '" r="1.6" fill="#e8e8e8"/>').join(''));`;
      break;
    case 'heatmap':
      body = `const g = gridOf(item, { series: ${series} });
if (!g) return '<div style="padding:6px;color:#8c8c8c">no grid at ' + esc(${series} || 'meta.grid') + '</div>';
const flat = g.rows.flat();
const lo = Math.min(...flat), hi = Math.max(...flat);
const cw = w / g.width, ch = h / g.height;
return svg(item, 'gen-heatmap', w, h, g.rows.map((row, y) => row.map((v, x) => {
  const a = hi === lo ? 0.5 : (v - lo) / (hi - lo);
  return '<rect x="' + (x * cw) + '" y="' + (y * ch) + '" width="' + cw + '" height="' + ch + '" fill="#fff" fill-opacity="' + (0.08 + a * 0.8).toFixed(3) + '"/>';
}).join('')).join(''));`;
      break;
    case 'table':
      body = `const data = item.data;
if (!data || !Array.isArray(data.columns) || !Array.isArray(data.rows)) return '<div style="padding:6px;color:#8c8c8c">no table data</div>';
const rows = data.rows.slice(0, spec.maxRows || 8);
return '<table class="md-table" style="font:10px/1.4 monospace;border-collapse:collapse;width:100%"><thead><tr>' + data.columns.map(c => '<th style="text-align:left;color:#8c8c8c;border-bottom:1px solid #5a5a5a;padding:2px 4px">' + esc(c.label || c.key) + '</th>').join('') + '</tr></thead><tbody>' + rows.map(r => '<tr>' + data.columns.map(c => '<td style="border-bottom:1px solid #2c2c2c;padding:2px 4px">' + esc(r[c.key] == null ? '—' : String(r[c.key])) + '</td>').join('') + '</tr>').join('') + '</tbody></table>';`;
      break;
    case 'slo':
      body = `const value = Number(Object.hasOwn(item, 'value') ? item.value : 0);
const target = Number((spec.targets && spec.targets[0] && spec.targets[0].value) ?? 100);
const ok = value >= target;
return '<div style="padding:8px;font:13px/1.45 ui-sans-serif,system-ui,sans-serif">' + '<div style="color:#f6f8fb;font-size:18px;font-variant-numeric:tabular-nums">' + esc(fmt(value)) + (spec.unit ? ' ' + esc(spec.unit) : '') + '</div>' + '<div style="color:' + (ok ? '#3dcc7a' : '#ff6d6d') + '">' + (ok ? '✓ at or above target' : '✕ below target') + '</div>' + '<div style="color:#9aa6b6">target ' + esc(fmt(target)) + (spec.unit ? ' ' + esc(spec.unit) : '') + '</div></div>';`;
      break;
  }
  return wrap(n, spec, body);
}

const BLOCKED: [RegExp, string][] = [
  [/\bimport\s*\(/, 'dynamic import'],
  [/\brequire\s*\(/, 'require'],
  [/\beval\s*\(/, 'eval'],
  [/\bnew\s+Function\b/, 'new Function'],
  [/\bfetch\s*\(/, 'fetch'],
  [/\bXMLHttpRequest\b/, 'XMLHttpRequest'],
  [/\bWebSocket\b/, 'WebSocket'],
  [/\bEventSource\b/, 'EventSource'],
  [/\blocalStorage\b/, 'localStorage'],
  [/\bsessionStorage\b/, 'sessionStorage'],
  [/document\.cookie/, 'document.cookie'],
  [/window\.open/, 'window.open'],
  [/\bparent\b/, 'parent frame access'],
  [/\btop\b/, 'top frame access'],
  [/\blocation\b/, 'location'],
  [/\bhistory\./, 'history'],
  [/\/api\//, 'direct API access'],
  [/<script/i, 'script tag'],
  [/<iframe/i, 'iframe'],
  [/<object/i, 'object tag'],
  [/<embed/i, 'embed tag'],
  [/\son\w+\s*=/i, 'inline event handler'],
  [/import\s+[^'"]+from/, 'module import'],
  [/export\s+.*\sfrom\s*['"]/, 'module re-export'],
];

/** static checks; the Electron render gate is a separate step */
export function validateViewCode(code: string): ViewValidation {
  const source = String(code ?? '');
  const errors: string[] = [];
  const warnings: string[] = [];
  const hash = sha256(source);
  if (!source.trim()) errors.push('code is empty');
  if (Buffer.byteLength(source) > VIEW_MAX_BYTES) errors.push(`code is too large (> ${VIEW_MAX_BYTES} bytes)`);
  if (!/export\s+function\s+render\s*\(/.test(source) && !/export\s+default\s+/.test(source)) errors.push('the module must export a render(ctx) function');
  for (const [re, label] of BLOCKED) if (re.test(source)) errors.push(`blocked: ${label}`);
  if (/innerHTML/.test(source)) warnings.push('innerHTML is used; prefer returning an escaped string');
  if (!/\besc\s*\(/.test(source)) warnings.push('no esc() call found; user text may not be escaped');
  // syntax check without executing the module
  try {
    const plain = source
      .replace(/^\s*export\s+default\s+function\s+(\w+)/gm, 'function $1')
      .replace(/^\s*export\s+default\s+/gm, 'const __default = ')
      .replace(/^\s*export\s+(const|let|var|function|class)\s+/gm, '$1 ');
    new Script(plain, { filename: 'view.js' });
  } catch (e) {
    errors.push(`syntax: ${(e as Error).message}`);
  }
  return { ok: errors.length === 0, errors: [...new Set(errors)], warnings: [...new Set(warnings)], sha256: hash };
}

export function readViewFile(name: string): string {
  const file = viewFilePath(name);
  if (!existsSync(file)) throw new HudError(404, `no view named ${name}`);
  const st = lstatSync(file);
  if (st.isSymbolicLink() || !st.isFile()) throw new HudError(403, 'view path is not a regular file');
  return readFileSync(file, 'utf8');
}

/** direct write used by the local generator and by an approved review. Caller-supplied source goes through `installUntrustedView`. */
export function writeViewFile(name: string, code: string, opts: { overwrite?: boolean; expectedSha256?: string } = {}): { sha256: string; mtime: number; path: string } {
  const file = viewFilePath(name);
  const validation = validateViewCode(code);
  if (!validation.ok) throw new HudError(400, `view did not validate: ${validation.errors.join('; ')}`, { code: 'invalid', errors: validation.errors });
  if (existsSync(file)) {
    if (!opts.overwrite) throw new HudError(409, `view ${name} already exists; pass overwrite`, { code: 'exists' });
    const current = sha256(readFileSync(file));
    if (opts.expectedSha256 && opts.expectedSha256 !== current) throw new HudError(409, 'view changed since you read it', { code: 'conflict', expected: opts.expectedSha256, actual: current });
  }
  const tmp = `${file}.${process.pid}.${Math.random().toString(36).slice(2)}.tmp`;
  mkdirSync(viewsDir(), { recursive: true });
  writeFileSync(tmp, code);
  renameSync(tmp, file);
  return { sha256: validation.sha256, mtime: statSync(file).mtimeMs, path: file };
}

const VIEW_REVIEW_TTL_MS = 15 * 60 * 1000;
export const MAX_VIEW_REVIEWS = 32;

/** a caller-supplied module staged for review. It is not installed, and it is not served. */
export interface ViewReview {
  installed: false;
  trust: 'untrusted';
  id: string;
  name: string;
  sha256: string;
  baseSha256: string | null;
  diff: string;
  added: number;
  removed: number;
  truncated: boolean;
  validation: ViewValidation;
  expiresAt: number;
  approvable: true;
}

/** staged source whose review does not fit in the caller's result budget. Nothing was kept to approve. */
export interface ViewReviewRefusal {
  installed: false;
  trust: 'untrusted';
  approvable: false;
  name: string;
  limit: number;
  reviewChars: number;
  text: string;
}

/** the module that landed after its review was approved. */
export interface ViewInstall {
  installed: true;
  trust: 'untrusted';
  name: string;
  sha256: string;
  mtime: number;
  path: string;
  proposalId: string;
}

interface StoredReview extends ViewReview {
  code: string;
}

const reviews = new Map<string, StoredReview>();

function expireReviews(now: number) {
  for (const [id, review] of reviews) if (review.expiresAt <= now) reviews.delete(id);
}

/** drop expired reviews, then the oldest ones, until another review can be stored */
function makeRoom(now: number) {
  expireReviews(now);
  while (reviews.size >= MAX_VIEW_REVIEWS) {
    const oldest = reviews.keys().next().value;
    if (oldest === undefined) break;
    reviews.delete(oldest);
  }
}

function readInstalled(name: string): { code: string; sha256: string } | null {
  try {
    const code = readViewFile(name);
    return { code, sha256: sha256(code) };
  } catch (e) {
    if (e instanceof HudError && e.status === 404) return null;
    throw e;
  }
}

export function formatViewReview(review: ViewReview): string {
  return [
    `NOT INSTALLED — untrusted view ${review.name} is waiting for approval`,
    `proposal ${review.id}`,
    `sha256 ${review.sha256}`,
    `Approve this exact module with proposal ${review.id} and sha256 ${review.sha256}.`,
    'Trust: this module runs unsandboxed in the board page. Only approve code you have reviewed.',
    `diff: +${review.added} -${review.removed}${review.truncated ? ' (truncated)' : ''}`,
    review.diff || '(no textual changes)',
  ].join('\n');
}

/** the hud_view write result: the approve recipe and the full diff, or nothing that can be approved */
export function formatAgentViewReview(review: ViewReview): string {
  return `hud_view {action:"approve", name:"${review.name}", proposalId:"${review.id}", sha256:"${review.sha256}"}\n${formatViewReview(review)}`;
}

/**
 * Stage caller-supplied renderer source, or install a previously staged review.
 * `approve` without a live proposal id never writes: the diff has to be surfaced first,
 * and the bytes that land are the bytes that were reviewed.
 */
export function installUntrustedView(name: string, body: {
  code?: string;
  overwrite?: boolean;
  expectedSha256?: string;
  approve?: boolean;
  proposalId?: string;
  sha256?: string;
  now?: number;
  ttlMs?: number;
  /** when set, a review that does not fit in this many characters is dropped instead of returned */
  maxChars?: number;
} = {}): ViewReview | ViewInstall | ViewReviewRefusal {
  const now = body.now ?? Date.now();
  if (body.approve === true) {
    if (!body.proposalId || !body.sha256) throw new HudError(409, 'untrusted modules cannot land without approval of a staged review', { code: 'approval-required' });
    if (typeof body.code === 'string' && sha256(body.code) !== body.sha256) throw new HudError(409, 'code does not match the reviewed module', { code: 'approval-required' });
    return approveReviewedView(name, body.proposalId, body.sha256, now);
  }
  if (typeof body.code !== 'string') throw new HudError(400, 'code is required');
  if (body.maxChars !== undefined && (!Number.isInteger(body.maxChars) || body.maxChars < 1)) throw new HudError(400, 'maxChars must be a positive integer');
  const review = buildViewReview(name, body.code, { overwrite: body.overwrite, expectedSha256: body.expectedSha256, now, ttlMs: body.ttlMs });
  if (body.maxChars !== undefined) {
    const text = formatAgentViewReview(review);
    if (text.length > body.maxChars) {
      // Never insert a review we are about to refuse: insertion prunes the oldest pending approval.
      return {
        installed: false,
        trust: 'untrusted',
        approvable: false,
        name: review.name,
        limit: body.maxChars,
        reviewChars: text.length,
        text: `NOT INSTALLED — untrusted view ${review.name} was not shown in full (${text.length} characters exceeds the ${body.maxChars} character review limit). No proposal was staged, so it cannot be approved. Shorten the module and submit it again.`,
      };
    }
  }
  makeRoom(now);
  reviews.set(review.id, { ...review, code: body.code });
  return review;
}

function buildViewReview(name: string, code: string, opts: { overwrite?: boolean; expectedSha256?: string; now: number; ttlMs?: number }): ViewReview {
  const n = normalizeViewName(name);
  const validation = validateViewCode(code);
  if (!validation.ok) throw new HudError(400, `view did not validate: ${validation.errors.join('; ')}`, { code: 'invalid', errors: validation.errors });
  const current = readInstalled(n);
  if (current && !opts.overwrite) throw new HudError(409, `view ${n} already exists; pass overwrite`, { code: 'exists' });
  if (current && opts.expectedSha256 && opts.expectedSha256 !== current.sha256) throw new HudError(409, 'view changed since you read it', { code: 'conflict', expected: opts.expectedSha256, actual: current.sha256 });
  const diff = unifiedDiff(current?.code ?? '', code);
  const review: ViewReview = {
    installed: false,
    trust: 'untrusted',
    id: randomUUID(),
    name: n,
    sha256: validation.sha256,
    baseSha256: current?.sha256 ?? null,
    diff: diff.text,
    added: diff.added,
    removed: diff.removed,
    truncated: diff.truncated,
    validation,
    expiresAt: opts.now + (opts.ttlMs ?? VIEW_REVIEW_TTL_MS),
    approvable: true,
  };
  return review;
}

function approveReviewedView(name: string, proposalId: string, hash: string, now: number): ViewInstall {
  const n = normalizeViewName(name);
  expireReviews(now);
  const review = reviews.get(proposalId);
  if (!review || review.expiresAt <= now) throw new HudError(404, 'no pending approval for that review', { code: 'approval-required' });
  if (review.name !== n) throw new HudError(409, 'proposal is for a different view', { code: 'approval-required' });
  if (hash !== review.sha256) throw new HudError(409, 'sha256 does not match the reviewed module', { code: 'approval-required' });
  const current = readInstalled(n);
  const base = current?.sha256 ?? null;
  if (base !== review.baseSha256) throw new HudError(409, 'view changed since it was reviewed', { code: 'conflict', expected: review.baseSha256, actual: base });
  const wrote = writeViewFile(n, review.code, { overwrite: base !== null, expectedSha256: base ?? undefined });
  reviews.delete(proposalId);
  return { installed: true, trust: 'untrusted', name: n, sha256: wrote.sha256, mtime: wrote.mtime, path: wrote.path, proposalId };
}

export function deleteViewFile(name: string, expectedSha256?: string): { deleted: boolean } {
  const file = viewFilePath(name);
  if (!existsSync(file)) throw new HudError(404, `no view named ${name}`);
  if (expectedSha256 && sha256(readFileSync(file)) !== expectedSha256) throw new HudError(409, 'view changed since you read it', { code: 'conflict' });
  rmSync(file);
  return { deleted: true };
}

export function listViewInfos(dir = viewsDir()): { name: string; file: string; mtime: number; bytes: number; sha256: string; validation: ViewValidation }[] {
  try {
    return readdirSync(dir)
      .filter((n) => VIEW_NAME_RE.test(n.replace(/\.js$/, '')) && n.endsWith('.js'))
      .map((n) => {
        const file = resolve(dir, n);
        const st = statSync(file);
        const code = readFileSync(file, 'utf8');
        return { name: n.replace(/\.js$/, ''), file, mtime: st.mtimeMs, bytes: st.size, sha256: sha256(code), validation: validateViewCode(code) };
      })
      .sort((a, b) => b.mtime - a.mtime);
  } catch {
    return [];
  }
}

