import { accessSync, chmodSync, closeSync, constants, existsSync, lstatSync, mkdirSync, openSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { isElectron } from './assets.ts';
import { config } from './config.ts';
import { bundledCli } from './electron-runtime.ts';

/**
 * The `hud` command the app installs on PATH.
 *
 * A wrapper script, not a symlink: a symlink to the app binary would launch the GUI, because it
 * cannot set ELECTRON_RUN_AS_NODE or point at the bundled CLI entry. The script `exec`s so MCP's
 * JSON-RPC over stdin/stdout passes straight through.
 */

const appExe = (): string => process.execPath;

function recordPath(): string {
  return join(config().dataDir, 'cli.json');
}

let tempCounter = 0;

/** Write beside the destination so the final rename is atomic on the same filesystem. */
function atomicWriteFile(path: string, contents: string, mode?: number): void {
  let temp: string | undefined;
  let fd: number | undefined;
  try {
    for (let attempt = 0; attempt < 20; attempt++) {
      const candidate = `${path}.${process.pid}.${++tempCounter}.tmp`;
      try {
        fd = openSync(candidate, 'wx');
        temp = candidate;
        break;
      } catch (e) {
        if ((e as NodeJS.ErrnoException).code !== 'EEXIST') throw e;
      }
    }
    if (fd === undefined || temp === undefined) throw new Error(`could not choose a temporary path for ${path}`);
    writeFileSync(fd, contents, 'utf8');
    if (mode !== undefined) chmodSync(temp, mode);
    closeSync(fd);
    fd = undefined;
    renameSync(temp, path);
    temp = undefined;
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch {}
    }
    if (temp !== undefined) {
      try { rmSync(temp); } catch {}
    }
  }
}

/** Repair an existing managed shim or recreate a missing recorded shim, never replace a foreign file. */
function recordedManagedShim(): string | null {
  try {
    const p = JSON.parse(readFileSync(recordPath(), 'utf8')).path;
    if (typeof p !== 'string') return null;
    try { lstatSync(p); } catch (error) { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return p; throw error; }
    return isOurShim(p) ? p : null;
  } catch {
    return null;
  }
}

/** absolute path of the `hud` command, if one was installed */
export function installedShim(): string | null {
  try {
    const p = JSON.parse(readFileSync(recordPath(), 'utf8')).path;
    if (typeof p === 'string' && existsSync(p)) return p;
  } catch {}
  // the shim may also have been moved onto PATH by hand
  if (process.env.HUD_SHIM && existsSync(process.env.HUD_SHIM)) return process.env.HUD_SHIM;
  return null;
}

function writable(dir: string): boolean {
  try {
    accessSync(dir, constants.W_OK);
    return true;
  } catch {
    return false;
  }
}

/** the preferred shim location for this platform, plus a PATH hint when it is a fallback */
function shimTarget(): { path: string; hint?: string } {
  // HUD_BIN_DIR lets a user (or a test) choose where the command goes
  if (process.env.HUD_BIN_DIR) {
    return { path: join(process.env.HUD_BIN_DIR, process.platform === 'win32' ? 'hud.cmd' : 'hud') };
  }
  if (process.platform === 'win32') {
    const dir = join(process.env.LOCALAPPDATA || join(homedir(), 'AppData', 'Local'), 'hud', 'bin');
    return { path: join(dir, 'hud.cmd'), hint: `add ${dir} to your PATH to run "hud" from any terminal` };
  }
  if (process.platform === 'darwin' && writable('/usr/local/bin')) return { path: '/usr/local/bin/hud' };
  const dir = join(homedir(), '.local', 'bin');
  return {
    path: join(dir, 'hud'),
    hint: writable('/usr/local/bin') ? undefined : `add ${dir} to your PATH (e.g. export PATH="${dir}:$PATH")`,
  };
}

/** marker proving a file is a shim we wrote; install/uninstall never touch anything without it */
const MARKER = 'generated by the hud app';

function shimBody(exe: string, entry: string, self: string): string {
  if (process.platform === 'win32') {
    const literal = (value: string) => value.replace(/%/g, '%%');
    return `@echo off\r\nsetlocal DisableDelayedExpansion\r\nrem hud — ${MARKER}. Re-run "Install hud command" after moving the app.\r\nset "ELECTRON_RUN_AS_NODE=1"\r\nset "HUD_SHIM=%~f0"\r\n"${literal(exe)}" "${literal(entry)}" %*\r\n`;
  }
  const quote = (value: string) => `'${value.replace(/'/g, "'\\''")}'`;
  return `#!/bin/sh\n# hud — ${MARKER}. Re-run "Install hud command" after moving the app.\nELECTRON_RUN_AS_NODE=1 HUD_SHIM=${quote(self)} exec ${quote(exe)} ${quote(entry)} "$@"\n`;
}

/** true if `p` is a regular file (not a symlink) that we generated */
function isOurShim(p: string): boolean {
  try {
    const st = lstatSync(p);
    return st.isFile() && readFileSync(p, 'utf8').slice(0, 400).includes(MARKER);
  } catch {
    return false;
  }
}

/** install the `hud` command; returns a one-line report */
export function installCli(): string {
  if (!isElectron()) return 'not running from the app — from a source checkout just use node bin/hud.js';
  if (process.env.APPIMAGE) return 'the hud command cannot be installed from an AppImage (its CLI path changes on every run)';
  const entry = bundledCli();
  const selected = shimTarget();
  const recorded = recordedManagedShim();
  const path = recorded || selected.path;
  const hint = path === selected.path ? selected.hint : undefined;
  let existing = false;
  try {
    lstatSync(path);
    existing = true;
  } catch {}
  if (existing && !isOurShim(path)) return `not installing: ${path} exists and was not created by hud (remove it first, or set HUD_BIN_DIR)`;
  mkdirSync(dirname(path), { recursive: true });
  atomicWriteFile(path, shimBody(appExe(), entry, path), process.platform === 'win32' ? undefined : 0o755);
  mkdirSync(config().dataDir, { recursive: true });
  atomicWriteFile(recordPath(), JSON.stringify({ path, entry, exe: appExe(), installedAt: Date.now() }, null, 2));
  return `installed ${path}${hint ? `\n  ${hint}` : ''}`;
}

/** remove the `hud` command; returns a one-line report */
export function uninstallCli(): string {
  let p: string | null = null;
  try {
    const rec = JSON.parse(readFileSync(recordPath(), 'utf8')).path;
    if (typeof rec === 'string') p = rec;
  } catch {}
  if (!p) return 'no hud command installed';
  if (!isOurShim(p)) {
    try {
      rmSync(recordPath());
    } catch {}
    return `left ${p} alone: it is missing or was not created by hud`;
  }
  try {
    rmSync(p);
  } catch (e) {
    return `could not remove ${p}: ${(e as Error).message}`;
  }
  try {
    rmSync(recordPath());
  } catch {}
  return `removed ${p}`;
}

export function cliStatus(): string {
  const p = installedShim();
  if (!p) return 'hud command: not installed';
  return `hud command: ${p}\n  entry: ${bundledCli()}\n  app:   ${appExe()}`;
}

/** Keep a previously installed managed command pointed at the current app after replacement. */
export function refreshInstalledCli(): void {
  if (recordedManagedShim() && isElectron() && !process.env.APPIMAGE && !cliInfo().ready) installCli();
}

function isExecutable(path: string): boolean {
  try {
    accessSync(path, process.platform === 'win32' ? constants.F_OK : constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

/** Structured, read-only state for the installed command shim. */
export function cliInfo(): { installed: boolean; ready: boolean; path: string | null; detail: string } {
  const path = installedShim();
  if (!isElectron()) {
    return {
      installed: path !== null,
      ready: false,
      path,
      detail: 'source: not running from the app; from a source checkout just use node bin/hud.js',
    };
  }
  if (process.env.APPIMAGE) {
    return {
      installed: path !== null,
      ready: false,
      path,
      detail: 'AppImage: the hud command cannot be installed from an AppImage (its CLI path changes on every run)',
    };
  }
  if (!path) return { installed: false, ready: false, path: null, detail: 'missing: no hud command is installed' };
  if (!isOurShim(path)) {
    return { installed: true, ready: false, path, detail: `stale: ${path} is missing or was not created by hud` };
  }

  const exe = appExe();
  const entry = bundledCli();
  let bodyMatches = false;
  try {
    bodyMatches = readFileSync(path, 'utf8') === shimBody(exe, entry, path);
  } catch {}
  if (!bodyMatches) {
    return { installed: true, ready: false, path, detail: `stale: ${path} points to a different app or CLI entry` };
  }
  if (!existsSync(exe) || !isExecutable(exe)) {
    return { installed: true, ready: false, path, detail: `stale: app executable is missing or not executable: ${exe}` };
  }
  if (!existsSync(entry)) {
    return { installed: true, ready: false, path, detail: `stale: CLI entry is missing: ${entry}` };
  }
  if (!isExecutable(path)) {
    return { installed: true, ready: false, path, detail: `stale: shim is not executable: ${path}` };
  }
  return { installed: true, ready: true, path, detail: `ready: ${path}` };
}
